# PlatformIO pre-script (same method as ../magi-esp/scripts/secrets.py): read ~/esp32-tools/wifi.secret (SSID=, PSK=)
# and write include/secrets.h (chmod 600, git-ignored) with C-escaped string literals. Never pass the secret via -D.
import os
Import("env")

def read(path):
    out = {}
    try:
        for line in open(os.path.expanduser(path), encoding="utf-8"):
            line = line.rstrip("\r\n")
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                out[k.strip()] = v
    except FileNotFoundError:
        pass
    return out

def c(s):
    # OCTAL escapes (always 3 digits): C hex escapes (\xNN) swallow any following hex digit and silently corrupt a password
    # such as 'x?ab' (found 2026-10-24 by cybrdek-mesh-writer). Tested against gcc, see canary-tests/test_secrets_escape.py
    return '"' + "".join(ch if (32 <= ord(ch) < 127 and ch not in '"\\?') else "\\%03o" % b for ch in s for b in ch.encode()) + '"'

w = read("~/esp32-tools/wifi.secret")
if "SSID" not in w:
    print("secrets.py: WARNING ~/esp32-tools/wifi.secret missing: building with placeholder Wi-Fi")
inc = os.path.join(env["PROJECT_DIR"], "include"); os.makedirs(inc, exist_ok=True)
path = os.path.join(inc, "secrets.h")
with open(path, "w") as f:
    f.write("// GENERATED by scripts/secrets.py, do not commit\n#pragma once\n")
    f.write("#define WIFI_SSID %s\n#define WIFI_PSK %s\n" % (c(w.get("SSID", "UNSET")), c(w.get("PSK", ""))))
os.chmod(path, 0o600)
